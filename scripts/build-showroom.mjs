#!/usr/bin/env node
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {picture,card} from '../assets/showroom/render.mjs';
const root=new URL('../',import.meta.url),source=JSON.parse(readFileSync(new URL('assets/showroom/v1/catalog.json',root),'utf8'));
writeFileSync(new URL('assets/showroom/data/product-definitions.mjs',root),'// Generated by scripts/build-showroom.mjs from v1/catalog.json.\nexport const productDefinitions = '+JSON.stringify(source.products,null,2)+';\n');
const {products}=await import('../assets/showroom/catalog.mjs');
const path=fileURLToPath(new URL('showroom/index.html',root));
let html=readFileSync(path,'utf8');
for(const [name,content]of Object.entries({products:products.map(card).join('\n'),hero:picture(products[0].image,products[0].image.alt,'sr-hero-image',true)})){
 const re=new RegExp(`<!-- showroom:${name} -->[\\s\\S]*?<!-- /showroom:${name} -->`);
 if(!re.test(html))throw new Error(`Missing showroom ${name} marker`);
 html=html.replace(re,`<!-- showroom:${name} -->\n${content}\n<!-- /showroom:${name} -->`);
}
writeFileSync(path,html);
console.log(`Showroom V1: ${products.length} selections using preserved photographs and documented presentation concepts.`);
