#!/usr/bin/env python3
"""Create responsive WebP copies; never modify the supplied PNG masters. Requires Pillow."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'assets'
source = json.loads((ASSETS / 'showroom/v1/catalog.json').read_text())
images = {image['src']: image for p in source['products'] for image in [p['image'], *p.get('gallery', [])]}
output = ASSETS / 'showroom/responsive'
output.mkdir(exist_ok=True)
manifest = {}
original_bytes = derived_bytes = 0
for src, item in images.items():
    master = ASSETS / src
    assert hashlib.sha256(master.read_bytes()).hexdigest() == item['sha256'], f'Original changed: {src}'
    original_bytes += master.stat().st_size
    with Image.open(master) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        assert image.size == (item['width'], item['height'])
        variants = []
        for width in sorted({min(w, image.width) for w in [480, 800, 1200, 1600]}):
            height = round(image.height * width / image.width)
            path = output / f'{master.stem}-{width}.webp'
            image.resize((width, height), Image.Resampling.LANCZOS).save(path, 'WEBP', quality=86, method=6)
            derived_bytes += path.stat().st_size
            variants.append({'src': str(path.relative_to(ASSETS)), 'width': width, 'height': height})
        manifest[src] = variants
(ASSETS / 'showroom/data/image-variants.mjs').write_text('// Generated by scripts/build-showroom-images.py. PNG masters are preserved.\nexport const imageVariants = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n')
print(json.dumps({'masters': len(images), 'masterBytes': original_bytes, 'allResponsiveBytes': derived_bytes, 'variants': sum(len(v) for v in manifest.values())}))
